def decode_text(text):
    if not text:
        return text
    res = text
    for k in sorted(GLYPH_MAP.keys(), key=lambda x: -len(x)):
        res = res.replace(k, GLYPH_MAP[k])
    
    # Post-processing fixes for clean Telugu
    # Fix repeated vowels/particles caused by legacy font combinations
    res = re.sub(r'నిని', 'ని', res)
    res = re.sub(r'ముము', 'ము', res)
    res = re.sub(r'లల', 'ల', res)
    res = re.sub(r'లులు', 'లు', res)
    res = re.sub(r'కుకు', 'కు', res)
    res = re.sub(r'కక', 'క్క', res)
    res = re.sub(r'నన', 'న్న', res)
    res = re.sub(r'తత', 'త్త', res)
    res = re.sub(r'దద', 'ద్ద', res)
    res = re.sub(r'పప', 'ప్ప', res)
    res = re.sub(r'మ్మమ', 'మ్మ', res)
    return res

if __name__ == '__main__':
    with open('questions_raw.json', 'r', encoding='utf-8') as f:
        questions = json.load(f)

    decoded_questions = []
    total_unmapped = 0
    unmapped_chars = Counter()

    for q in questions:
        new_q = dict(q)
        new_q['stem'] = decode_text(q['stem'])
        new_q['correctText'] = decode_text(q['correctText'])
        new_q['options'] = [
            {'number': o['number'], 'text': decode_text(o['text'])}
            for o in q['options']
        ]
        if 'sourceText' in new_q:
            new_q['sourceText'] = decode_text(q['sourceText'])
        
        decoded_questions.append(new_q)

        for field in [new_q['stem'], new_q['correctText']] + [o['text'] for o in new_q['options']]:
            bad = re.findall(r'[^\x00-\x7F\u0C00-\u0C7F\s\.,;:!?\"\'\(\)\[\]\{\}\u2013\u2014\-0-9\/\\]', field)
            total_unmapped += len(bad)
            unmapped_chars.update(bad)

    print(f"Total unmapped characters remaining: {total_unmapped}")
    print("Top unmapped:")
    for c, cnt in unmapped_chars.most_common(20):
        print(f"  {c} (U+{ord(c):04X}): {cnt}")

    with open('questions_decoded.json', 'w', encoding='utf-8') as f:
        json.dump(decoded_questions, f, ensure_ascii=False, indent=2)
    print("Saved questions_decoded.json successfully.")
