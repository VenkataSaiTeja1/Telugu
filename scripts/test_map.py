def decode_text(text):
    if not text:
        return text
    res = text
    # Replace sorted by key length descending
    for k in sorted(GLYPH_MAP.keys(), key=lambda x: -len(x)):
        res = res.replace(k, GLYPH_MAP[k])
    return res

total_unmapped = 0
unmapped_chars = Counter()

for q in questions:
    for field in [q['stem'], q['correctText']] + [o['text'] for o in q['options']]:
        decoded = decode_text(field)
        bad = re.findall(r'[^\x00-\x7F\u0C00-\u0C7F\s\.,;:!?\"\'\(\)\[\]\{\}\u2013\u2014\-0-9\/\\]', decoded)
        total_unmapped += len(bad)
        unmapped_chars.update(bad)

print(f"Total unmapped characters remaining: {total_unmapped}")
print(f"Top 30 remaining unmapped characters:")
for c, cnt in unmapped_chars.most_common(30):
    print(f"  {c} (U+{ord(c):04X}): {cnt}")
